"""Build the flowering specimen at (7.15,113) on the east campus avenue."""
import math
import random
import sys
from pathlib import Path

import bpy
import numpy as np
from mathutils import Vector

CAMPUS = Path(__file__).resolve().parents[2]
SCALE = 1.0
CROWN_SHOULDER = (2.12, 3.09)
rng = random.Random(140713)
tau = math.tau
up = Vector((0, 0, 1))


def linear(rgb):
    return tuple(((v / 255 + .055) / 1.055) ** 2.4 if v > 10 else v / 3294.6 for v in rgb)


def basis(normal):
    n = normal.normalized()
    a = n.cross(up if abs(n.z) < .9 else Vector((0, 1, 0))).normalized()
    return a, n.cross(a).normalized()


class Surface:
    def __init__(self, name):
        self.name = name
        self.verts, self.faces, self.colors, self.uv = [], [], [], []

    def vertex(self, v, color=(1, 1, 1), uv=(0, 0)):
        self.verts.append(tuple(v))
        self.colors.append((*color, 1.0))
        self.uv.append(uv)
        return len(self.verts) - 1

    def finish(self, texture=None):
        mesh = bpy.data.meshes.new(self.name)
        mesh.from_pydata(self.verts, [], self.faces)
        mesh.update()
        mat = bpy.data.materials.new(self.name)
        mat.use_nodes = True
        bs = mat.node_tree.nodes.get("Principled BSDF")
        bs.inputs["Roughness"].default_value = .85
        if texture:
            uv = mesh.uv_layers.new(name="Corolla")
            uv.data.foreach_set("uv", np.array([self.uv[l.vertex_index] for l in mesh.loops], np.float32).ravel())
            node = mat.node_tree.nodes.new("ShaderNodeTexImage")
            node.image = texture
            mat.node_tree.links.new(node.outputs["Color"], bs.inputs["Base Color"])
            cutout = mat.node_tree.nodes.new("ShaderNodeMath")
            cutout.operation = "GREATER_THAN"
            cutout.inputs[1].default_value = .45
            mat.node_tree.links.new(node.outputs["Alpha"], cutout.inputs[0])
            mat.node_tree.links.new(cutout.outputs[0], bs.inputs["Alpha"])
            mat.alpha_threshold = .45
        else:
            col = mesh.color_attributes.new(name="Pigment", type="FLOAT_COLOR", domain="POINT")
            col.data.foreach_set("color", np.asarray(self.colors, np.float32).ravel())
            node = mat.node_tree.nodes.new("ShaderNodeVertexColor")
            node.layer_name = col.name
            mat.node_tree.links.new(node.outputs["Color"], bs.inputs["Base Color"])
        mesh.materials.append(mat)
        obj = bpy.data.objects.new(self.name, mesh)
        bpy.context.collection.objects.link(obj)
        for face in mesh.polygons:
            face.use_smooth = True


def petal_image():
    # Overlapping individual petals, painted from the outside toward the throat.
    size = 256
    y, x = (np.mgrid[:size, :size] + .5) / size * 2 - 1
    pixels = np.zeros((size, size, 4), np.float32)
    pixels[:, :, :3] = linear((239, 180, 194))
    for count, reach, breadth, offset, deep, pale in [
        (11, .93, .32, .21, (177, 99, 128), (250, 202, 210)),
        (10, .76, .30, .52, (182, 90, 125), (251, 192, 204)),
        (8, .58, .25, .08, (176, 77, 112), (245, 178, 199)),
        (7, .39, .18, .36, (165, 75, 108), (243, 162, 182)),
        (5, .23, .12, .14, (158, 75, 96), (233, 155, 168))]:
        for i in range(count):
            a = offset + tau*i/count + rng.uniform(-.1, .1)
            length = reach*rng.uniform(.94, 1.04)
            t = (x*math.cos(a)+y*math.sin(a))/length
            s = (-x*math.sin(a)+y*math.cos(a)) / breadth
            width = np.maximum(0, np.sin(np.clip(t,0,1)**1.55 * math.pi))**.49
            edge = 1 + .055*np.cos(s*13 + a) + .025*np.cos(s*25)
            mask = (t > .045) & (t < 1-.034*np.exp(-(s/.22)**2)) & (abs(s) < width*edge)
            folds = .10*np.sin(s*14+t*2+a) + .05*np.cos(s*26)
            light = np.clip(.21 + .70*t + .10*s + folds, 0, 1)[...,None]
            col = np.array(linear(deep))*(1-light) + np.array(linear(pale))*light
            pixels[mask, :3] = col[mask]
            pixels[mask, 3] = 1
    for i in range(14):
        a = tau*i/14
        r = rng.uniform(.032,.105)
        mask = (x-r*math.cos(a))**2 + (y-r*math.sin(a))**2 < rng.uniform(.011,.023)**2
        pixels[mask, :3] = linear((236,186,128))
        pixels[mask, 3] = 1
    # Generated byte images receive encoded channel values when packed.
    encoded = np.clip(1.055*pixels[:, :, :3]**(1/2.4)-.055, 0, 1)
    pixels[:, :, :3] = encoded * np.array([.98,.90,.94])
    image = bpy.data.images.new("DoubleCherry_corolla", width=size, height=size, alpha=True)
    image.pixels.foreach_set(pixels.ravel())
    image.pack()
    return image


def crown_position(p):
    # Distribute branch centres, preserving flower diameter and blade length.
    low, high = CROWN_SHOULDER
    t = max(0.0, min(1.0,(p.z-low)/(high-low)))
    t = t*t*(3-2*t)
    flare = max(0.0,min(1.0,(p.z-low*.52)/(low*.40)))
    return Vector((p.x*(1+.04*flare-.16*t),p.y*(1+.15*flare-.35*t),p.z))


def limb(mesh, points, radii, sides, scale_structure=True):
    if scale_structure:
        points = [crown_position(p)*SCALE for p in points]
        radii = [r*SCALE for r in radii]
    phase = rng.random()*tau
    grain = [rng.uniform(.76, 1.16) for _ in range(sides)]
    rows = []
    for j, (p, radius) in enumerate(zip(points, radii)):
        direction = (points[min(j+1,len(points)-1)]-points[max(j-1,0)]).normalized()
        if j == 0:
            a, b = basis(direction)
        else:
            a = (a-direction*a.dot(direction)).normalized()
            b = direction.cross(a).normalized()
        ring = []
        for k in range(sides):
            angle = phase + tau*k/sides
            loc = p + radius*(a*math.cos(angle)+b*math.sin(angle))*(.97+.06*math.sin(3*angle))
            wash = max(0,min(1,(.87+.045*math.sin(angle*3+.7)-loc.z)/.065))
            tint = (bark_color*(1-wash) + wash_color*wash)*grain[k]*rng.uniform(.94,1.06)
            ring.append(mesh.vertex(loc,tint))
        if rows:
            for k in range(sides):
                m = (k+1)%sides
                mesh.faces.append((rows[-1][k],rows[-1][m],ring[m],ring[k]))
                if mesh is bark and (k+j)%3 == 0:
                    # Small horizontal lenticels track the actual tapered surface.
                    low = Vector(mesh.verts[rows[-1][k]])
                    high = Vector(mesh.verts[ring[k]])
                    other = Vector(mesh.verts[rows[-1][m]]).lerp(Vector(mesh.verts[ring[m]]),.49)
                    mid = low.lerp(high,.49).lerp(other,.49)
                    normal = (mid-points[j-1]).cross(direction).cross(-direction).normalized()
                    mid += normal*.0015
                    width = (other-low.lerp(high,.49))*.44
                    c = linear((118,91,80) if mid.z>.90 else (154,150,137))
                    ids = [twigs.vertex(v,c) for v in (mid-width,mid+direction*.003,mid+width,mid-direction*.002)]
                    twigs.faces.append(tuple(ids))
        rows.append(ring)
    mesh.faces.append(tuple(rows[-1]))


def along(pts, t):
    u = min(t,.999999)*(len(pts)-1)
    j = int(u)
    return pts[j].lerp(pts[j+1], u-j)


def leaf(p, direction, length):
    axis = direction.normalized()
    w = axis.cross(up).normalized()*length*.235
    color = np.array(linear(rng.choice([(137,133,57),(150,128,62),(153,143,65),(134,146,67),(170,136,72),(111,126,61)])))
    tip = leaves.vertex(p+axis*length-up*.012,color*.85)
    start = leaves.vertex(p,color*.73)
    ridge = leaves.vertex(p+axis*length*.49+up*.008,color*1.22)
    for side in [-1,1]:
        last = start
        for t, breadth in [(.23,.67),(.43,1),(.49,.89),(.57,.96),(.72,.70),(.8,.52)]:
            v = leaves.vertex(p+axis*length*t+w*breadth*side,color*(.83 if side<0 else .98))
            leaves.faces.append((last,v,ridge) if side>0 else (ridge,v,last))
            last = v
        leaves.faces.append((last,tip,ridge) if side>0 else (ridge,tip,last))


def bloom(center, normal, radius):
    n = normal.normalized()
    a,b = basis(n)
    phase = rng.random()*tau
    hub = flowers.vertex(center+n*radius*.38, uv=(.5,.5))
    outer = []
    for k in range(8):
        ang = tau*k/8
        # Octagon encloses the painted silhouette. A shallow bowl catches side light.
        u,v = math.cos(ang)*1.08,math.sin(ang)*1.08
        pt = center+radius*1.08*(math.cos(ang+phase)*a+math.sin(ang+phase)*b)+n*radius*.13*math.sin(3*ang+phase)
        outer.append(flowers.vertex(pt, uv=(.5+u*.5,.5+v*.5)))
    for i in range(8):
        flowers.faces.append((hub,outer[i],outer[(i+1)%8]))


def spray(points):
    for j in range(rng.randint(6,9) if SCALE > 1 else rng.randint(4,7)):
        t = min(.99, .09 + j*(.105 if SCALE > 1 else .145) + rng.uniform(-.03,.04))
        joint = crown_position(along(points,t))*SCALE
        a = rng.random()*tau
        side = Vector((math.cos(a),math.sin(a),rng.uniform(-.55,.05)))
        bunch = joint + side*.045 - up*rng.uniform(.035,.065)
        limb(twigs,[joint,bunch],[.0025,.0016],4,scale_structure=False)
        for k in range(rng.randint(4,7)):
            angle = tau*k/5 + a + rng.uniform(-.36,.36)
            n = Vector((math.cos(angle),math.sin(angle),rng.uniform(-1.35,.7))).normalized()
            bloom(bunch+n*rng.uniform(.017,.040),n,rng.uniform(.028,.044))
        for k in range(rng.choice([1,2,2,3])):
            angle = a + k*2.5
            leaf(joint,Vector((math.cos(angle),math.sin(angle),rng.uniform(-.25,.7))),rng.uniform(.075,.134))


def save_asset(name):
    bpy.context.preferences.filepaths.save_version = 0
    bpy.ops.wm.save_as_mainfile(filepath=str(CAMPUS/"blender"/"source"/(name+".blend")),compress=True)
    bpy.ops.export_scene.gltf(filepath=str(CAMPUS/"godot"/"assets"/(name+".glb")),export_format="GLB",export_yup=True)


def flower_branches(arm, heading, whorl, count):
    """Flower along both flanks of each limb, including its overhanging tips."""
    forward = Vector((math.cos(heading), math.sin(heading), 0))
    across = up.cross(forward)
    reach, rise = ((1.08, .22), (.83, .36), (.53, .36))[whorl]
    for j in range(count):
        t = .24 + .73*j/(count-1) + rng.uniform(-.023,.023)
        base = along(arm,t)
        angle = (-1 if j%2 else 1)*rng.uniform(.36,1.37)
        d = forward*math.cos(angle) + across*math.sin(angle)
        side = up.cross(d)
        length = reach*rng.uniform(.67,1.12)
        lift = rise+rng.uniform(-.15,.24)
        droop = (.34,.18,.05)[whorl]*t
        end = base+d*length+up*(lift-droop)
        branch = [base,base+d*(.33*length)+up*(.50*lift+.07),
                  base+d*(.73*length)+up*(.91*lift+.03),end]
        limb(twigs,branch,[.023,.017,.009,.003],6)
        for k in range(7):
            joint = along(branch,.11+.14*k+rng.uniform(-.018,.017))
            v = (d*rng.uniform(.4,1)+side*((-1)**k)*rng.uniform(.40,1.09)).normalized()
            span = rng.uniform(.30,.58)*(.90 if whorl==2 else 1)
            lift2 = rng.uniform(-.20,.26) + whorl*.025
            shoot = [joint,joint+v*(span*.49)+up*(lift2*.48+.048),joint+v*span+up*lift2]
            limb(twigs,shoot,[.007,.004,.0018],5)
            spray(shoot)
            if k%2==0 or rng.random()<.48:
                fork = along(shoot,.40)
                tip = fork+v*.20-side*((-1)**k)*rng.uniform(.20,.35)+up*rng.uniform(-.12,.21)
                sub = [fork,fork.lerp(tip,.53)+up*.04,tip]
                limb(twigs,sub,[.004,.0026,.0013],4)
                spray(sub)


def scaffold(origin, heading, reach, top, tier):
    angle = math.radians(heading)
    forward = Vector((math.cos(angle), math.sin(angle),0))
    across = up.cross(forward)
    path = [origin]
    # Low limbs lift first, flatten, then bend under the blossom weight.
    vertical = [(.48,.85,1.07,1.0),(.36,.67,.91,1.),(.30,.61,.84,1.)][tier]
    for (t,wobble),z in zip([(.17,.05),(.40,-.06),(.72,.09),(1,-.04)],vertical):
        path.append(origin+forward*reach*t+across*wobble+up*((top-origin.z)*z))
    limb(bark,path,[.084,.069,.049,.030,.010],9)
    return path,angle


def build_natural(tall=False):
    global bark, twigs, flowers, leaves, bark_color, wash_color, SCALE
    SCALE = 1.5 if tall else 1.0
    rng.seed(671923 if tall else 140713)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    bark,twigs,flowers,leaves = [Surface(n) for n in ("AS06_Bark","AS06_Twigs","AS06_DoubleFlowers","AS06_BronzeLeaves")]
    bark_color, wash_color = np.array(linear((82,60,54))), np.array(linear((178,174,160)))
    trunk = [Vector(p) for p in [(0,0,.015),(.012,.02,.19),(-.02,.035,.48),(-.045,.04,.69),(-.038,.04,.87),(.055,.03,1.13)]]
    limb(bark,trunk,[.196,.14,.121,.12,.113,.086],16)
    for k in range(6):
        a = k*tau/6+rng.uniform(-.29,.29)
        d = Vector((math.cos(a),math.sin(a),0))
        limb(bark,[trunk[1]-d*.04,d*.145+up*.095,d*rng.uniform(.27,.37)+up*.018],[.085,.067,.012],7)

    turn = 21 if tall else -8
    lower = []
    for heading,reach,top,start in [(8,2.20,1.96,.69),(79,1.94,2.18,.77),
            (153,2.13,2.10,.82),(219,2.31,1.99,.86),(289,2.05,2.30,.94)]:
        path,angle = scaffold(along(trunk,start),heading+turn,reach,top,0)
        lower.append(path)
        flower_branches(path,angle,0,9)
    middle = []
    for index,heading,reach,top in [(0,39,1.24,2.98),(1,120,1.29,2.85),
            (3,203,1.12,3.10),(4,305,1.28,2.88)]:
        path,angle = scaffold(along(lower[index],.31),heading+turn,reach,top,1)
        middle.append(path)
        flower_branches(path,angle,1,7)
    for idx,heading,reach,top in [(0,163,.64,3.91),(3,78,.48,3.59)]:
        path,angle = scaffold(along(middle[idx],.46),heading+turn,reach,top,2)
        flower_branches(path,angle,2,6)

    bark.finish()
    twigs.finish()
    leaves.finish()
    flowers.finish(petal_image())
    save_asset("sakura_tree_as06_tall" if tall else "sakura_tree_as06_01")


if __name__ == "__main__":
    build_natural("--tall" in sys.argv)
